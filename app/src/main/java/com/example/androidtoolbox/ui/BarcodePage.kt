private data class CodeDraft(val content: String, val format: CodeFormat?, val size: Int,
    val correction: ErrorCorrectionLevel, val color: Int, val showText: Boolean)

@Composable
internal fun QrPage(
    scanned: CodeResult?, onScan: () -> Unit, onSave: (Bitmap) -> Unit, onShare: (Bitmap) -> Unit,
    onCopy: (String, String) -> Unit, onImage: () -> Unit, back: () -> Unit,
) {
    var mode by rememberSaveable { mutableIntStateOf(0) }
    var barcode by rememberSaveable { mutableStateOf(false) }
    var formatName by rememberSaveable { mutableStateOf(CodeFormat.CODE128.name) }
    var kind by rememberSaveable { mutableStateOf("网址") }
    var content by remember { mutableStateOf("https://example.com") }
    var barcodeText by remember { mutableStateOf("TOOLBOX-2026") }
    var wifiName by remember { mutableStateOf("") }
    var wifiPassword by remember { mutableStateOf("") }
    var wifiSecurity by rememberSaveable { mutableStateOf("WPA") }
    var hidden by rememberSaveable { mutableStateOf(false) }
    var showPassword by rememberSaveable { mutableStateOf(false) }
    var recipient by remember { mutableStateOf("") }
    var subject by remember { mutableStateOf("") }
    var message by remember { mutableStateOf("") }
    var name by remember { mutableStateOf("") }
    var phone by remember { mutableStateOf("") }
    var email by remember { mutableStateOf("") }
    var company by remember { mutableStateOf("") }
    var size by rememberSaveable { mutableIntStateOf(1024) }
    var correctionName by rememberSaveable { mutableStateOf("M") }
    var colorName by rememberSaveable { mutableStateOf("墨黑") }
    var showText by rememberSaveable { mutableStateOf(true) }
    var error by remember { mutableStateOf<String?>(null) }
    val scope = rememberForegroundScope()
    var bitmap by remember { mutableStateOf<Bitmap?>(null) }
    var working by remember { mutableStateOf(false) }
    var generated by remember { mutableStateOf<CodeDraft?>(null) }
    var expanded by remember { mutableStateOf(false) }
    val format = CodeFormat.valueOf(formatName)
    val correction = ErrorCorrectionLevel.valueOf(correctionName)
    val colors = linkedMapOf("墨黑" to 0xFF000000.toInt(), "深蓝" to 0xFF273252.toInt(), "墨绿" to 0xFF145545.toInt())

    fun draft(): CodeDraft {
        val text = if (barcode) barcodeText else when (kind) {
            "网址" -> QrContent.website(content)
            "Wi-Fi" -> QrContent.wifi(wifiName, wifiPassword, wifiSecurity, hidden)
            "邮件" -> QrContent.email(recipient, subject, message)
            "短信" -> QrContent.sms(phone, message)
            "联系人" -> QrContent.contact(name, phone, email, company)
            else -> content.also { require(it.isNotBlank()) { "请输入二维码内容" } }
        }
        if (barcode) BarcodeCodec.normalize(text, format)
        return CodeDraft(text, if (barcode) format else null, size,
            if (barcode) ErrorCorrectionLevel.M else correction,
            if (barcode) android.graphics.Color.BLACK else colors.getValue(colorName), if (barcode) showText else false)
    }
    val current = runCatching { draft() }.getOrNull()
    val fresh = bitmap != null && generated == current && !working
    LaunchedEffect(scanned) { if (scanned != null) mode = 1 }
    fun generate(task: CodeDraft) {
        if (working) return
        working = true; bitmap = null; generated = null; error = null
        scope.launch {
            try {
                bitmap = withContext(Dispatchers.Default) {
                    if (task.format == null) QrCodec.generate(task.content, task.size, task.correction, task.color)
                    else BarcodeCodec.generate(task.content, task.format, task.size, task.showText)
                }
                generated = task
            } catch (e: CancellationException) {
                throw e
            } catch (_: OutOfMemoryError) {
                error = "内存不足，请选择较小的尺寸"
            } catch (e: Exception) {
                error = e.message ?: "生成失败，请检查输入内容"
            } finally { working = false }
        }
    }
    fun reuse(asQr: Boolean) {
        val value = scanned ?: return
        val original = CodeFormat.entries.firstOrNull { it.zxing == value.format }
        barcode = !asQr && original != null
        if (barcode) { formatName = original!!.name; barcodeText = value.text }
        else { kind = "文本"; content = value.text }
        mode = 0; error = null
    }

    Column {
        Header("二维码 / 条形码", "生成、图片解析与相机扫码 · 全部离线完成", back)
        LazyColumn(Modifier.fillMaxSize().padding(horizontal = 22.dp), verticalArrangement = Arrangement.spacedBy(14.dp)) {
            item { CodeChoices(listOf("生成", "扫描解析"), if (mode == 0) "生成" else "扫描解析") { mode = if (it == "生成") 0 else 1 } }
            if (mode == 0) {
                item { CodeChoices(listOf("二维码", "条形码"), if (barcode) "条形码" else "二维码") { barcode = it == "条形码"; error = null } }
                if (barcode) {
                    item {
                        CodeCard {
                            Text("条形码格式", color = Ink, fontWeight = FontWeight.Bold)
                            var menu by remember { mutableStateOf(false) }
                            Box {
                                OutlinedButton({ menu = true }, modifier = Modifier.fillMaxWidth()) { Text("${format.label}  ▾") }
                                DropdownMenu(menu, { menu = false }) {
                                    CodeFormat.entries.forEach { option ->
                                        DropdownMenuItem(text = { Text(option.label) }, onClick = { formatName = option.name; menu = false; error = null })
                                    }
                                }
                            }
                            Text(format.rule, color = Muted, fontSize = 12.sp)
                            CodeField(barcodeText, { barcodeText = it }, "条形码内容", singleLine = true)
                            TextButton({ barcodeText = format.example; error = null }) { Text("填入 ${format.label} 示例") }
                            CodeSwitch("在图片下方显示编号", showText) { showText = it }
                        }
                    }
                } else {
                    item { CodeChoices(listOf("网址", "文本", "Wi-Fi", "联系人", "邮件", "短信"), kind) { kind = it; error = null } }
                    item {
                        CodeCard {
                            when (kind) {
                                "Wi-Fi" -> {
                                    CodeField(wifiName, { wifiName = it }, "网络名称（SSID）", true)
                                    CodeChoices(listOf("WPA / WPA2", "WEP", "无密码"), when (wifiSecurity) { "WPA" -> "WPA / WPA2"; "WEP" -> "WEP"; else -> "无密码" }) {
                                        wifiSecurity = when (it) { "WPA / WPA2" -> "WPA"; "WEP" -> "WEP"; else -> "nopass" }
                                    }
                                    if (wifiSecurity != "nopass") {
                                        OutlinedTextField(wifiPassword, { if (it.length <= 8192) wifiPassword = it }, modifier = Modifier.fillMaxWidth(), singleLine = true,
                                            label = { Text("Wi-Fi 密码") }, visualTransformation = if (showPassword) VisualTransformation.None else PasswordVisualTransformation(),
                                            trailingIcon = { TextButton({ showPassword = !showPassword }) { Text(if (showPassword) "隐藏" else "显示") } })
                                    }
                                    CodeSwitch("隐藏网络", hidden) { hidden = it }
                                }
                                "联系人" -> {
                                    CodeField(name, { name = it }, "姓名", true)
                                    CodeField(phone, { phone = it }, "电话（可选）", true)
                                    CodeField(email, { email = it }, "邮箱（可选）", true)
                                    CodeField(company, { company = it }, "公司（可选）", true)
                                }
                                "邮件" -> {
                                    CodeField(recipient, { recipient = it }, "收件邮箱", true)
                                    CodeField(subject, { subject = it }, "邮件主题", true)
                                    CodeField(message, { message = it }, "邮件正文")
                                }
                                "短信" -> {
                                    CodeField(phone, { phone = it }, "手机号码", true)
                                    CodeField(message, { message = it }, "短信内容")
                                }
                                else -> {
                                    CodeField(content, { content = it }, if (kind == "网址") "完整网址（https://…）" else "文本内容", kind == "网址")
                                    Text("${content.toByteArray(Charsets.UTF_8).size} 字节 · 支持中文与换行", color = Muted, fontSize = 12.sp)
                                }
                            }
                        }
                    }
                }
                item {
                    CodeCard {
                        Text("图片设置", color = Ink, fontWeight = FontWeight.Bold)
                        Text(if (barcode) "目标宽度" else "图片边长", color = Muted, fontSize = 12.sp)
                        CodeChoices(listOf("512 px", "1024 px", "2048 px"), "$size px") { size = it.substringBefore(' ').toInt() }
                        if (!barcode) {
                            Text("容错等级", color = Muted, fontSize = 12.sp)
                            CodeChoices(listOf("L · 7%", "M · 15%", "Q · 25%", "H · 30%"),
                                when (correctionName) { "L" -> "L · 7%"; "Q" -> "Q · 25%"; "H" -> "H · 30%"; else -> "M · 15%" }) { correctionName = it.take(1) }
                            Text("等级越高，可恢复的污损越多，相同内容的码点也越密。", color = Muted, fontSize = 11.sp)
                            CodeChoices(colors.keys.toList(), colorName) { colorName = it }
                        } else Text("黑白高对比输出，自动保留左右留白；密集内容会自动加宽。", color = Muted, fontSize = 12.sp)
                    }
                }
                item {
                    PrimaryButton(if (working) "正在生成…" else if (barcode) "生成条形码" else "生成二维码", {
                        runCatching { draft() }.onSuccess { task ->
                            error = null
                            generate(task)
                        }.onFailure { error = it.message }
                    }, enabled = !working)
                    error?.let { Text(it, color = MaterialTheme.colorScheme.error, modifier = Modifier.padding(top = 8.dp), fontSize = 12.sp) }
                }
                item {
                    CodeCard {
                        val image = bitmap
                        if (image != null) {
                            Image(image.asImageBitmap(), "生成预览", Modifier.fillMaxWidth().height(if (generated?.format == null) 240.dp else 160.dp), contentScale = ContentScale.Fit)
                            Text("${image.width} × ${image.height} px · PNG", color = Muted, fontSize = 12.sp)
                            if (!fresh) Text("内容或设置已修改，请重新生成后保存。", color = MaterialTheme.colorScheme.primary, fontSize = 12.sp)
                        } else Box(Modifier.fillMaxWidth().height(130.dp), contentAlignment = Alignment.Center) {
                            if (working) CircularProgressIndicator() else Text("填写内容后点击生成，预览将在这里显示", color = Muted, fontSize = 12.sp)
                        }
                        Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceEvenly) {
                            TextButton({ bitmap?.let(onSave) }, enabled = fresh) { Text("保存 PNG") }
                            TextButton({ bitmap?.let(onShare) }, enabled = fresh) { Text("分享") }
                            TextButton({ expanded = true }, enabled = fresh) { Text("放大查看") }
                        }
                        if (fresh) TextButton({ generated?.let { onCopy("编码内容", if (it.format == null) it.content else BarcodeCodec.normalize(it.content, it.format)) } }) { Text("复制编码内容") }
                    }
                }
            } else {
                item {
                    CodeCard {
                        Text("识别二维码与条形码", color = Ink, fontWeight = FontWeight.Bold)
                        Text("支持 QR Code、Code 128 / 39 / 93、EAN-13 / 8、UPC-A / E、ITF、Codabar。每次读取一张图片中的一个码。", color = Muted, fontSize = 12.sp)
                        PrimaryButton("选择图片 · 离线解析", { mode = 1; onImage() })
                        OutlinedButton({ mode = 1; onScan() }, modifier = Modifier.fillMaxWidth()) { Text("相机扫码") }
                        Text("请保留完整码图和四周留白，条形码可横向或纵向识别。", color = Muted, fontSize = 12.sp)
                    }
                }
                scanned?.let { result ->
                    item {
                        CodeCard {
                            Text("解析结果", color = Ink, fontWeight = FontWeight.Bold)
                            Text("${result.formatLabel} · ${result.typeLabel}", color = Indigo, fontSize = 13.sp)
                            val parsed = remember(result) { result.parsed }
                            if (parsed.displayResult != result.text) {
                                SelectionContainer { Text(parsed.displayResult, color = Ink) }
                                HorizontalDivider()
                                Text("原始内容", color = Muted, fontSize = 12.sp)
                            }
                            SelectionContainer { Text(result.text, color = Ink) }
                            Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceEvenly) {
                                TextButton({ onCopy("扫码内容", result.text) }) { Text("复制内容") }
                                TextButton({ reuse(true) }) { Text("转为二维码") }
                            }
                            if (result.format != BarcodeFormat.QR_CODE && CodeFormat.entries.any { it.zxing == result.format })
                                OutlinedButton({ reuse(false) }, modifier = Modifier.fillMaxWidth()) { Text("按原码制重新生成") }
                        }
                    }
                }
            }
            item { Spacer(Modifier.height(24.dp)) }
        }
    }
    if (expanded && bitmap != null) {
        val image = bitmap!!
        var zoom by remember { mutableFloatStateOf(1f) }
        var pan by remember { mutableStateOf(Offset.Zero) }
        Dialog({ expanded = false }, properties = DialogProperties(usePlatformDefaultWidth = false, decorFitsSystemWindows = false)) {
            Surface(Modifier.fillMaxSize(), color = Color(0xFF121826)) {
                Column(Modifier.fillMaxSize().safeDrawingPadding()) {
                    Row(Modifier.fillMaxWidth().padding(horizontal = 16.dp), verticalAlignment = Alignment.CenterVertically) {
                        Text("码图预览", color = Color.White, modifier = Modifier.weight(1f))
                        TextButton({ zoom = 1f; pan = Offset.Zero }) { Text("重置", color = Color.White) }
                        TextButton({ expanded = false }) { Text("关闭", color = Color.White) }
                    }
                    Box(Modifier.fillMaxWidth().weight(1f).clipToBounds().pointerInput(Unit) {
                        detectTransformGestures { _, move, scale, _ ->
                            zoom = (zoom * scale).coerceIn(1f, 6f)
                            pan = if (zoom <= 1f) Offset.Zero else pan + move
                        }
                    }) {
                        Image(image.asImageBitmap(), "可双指缩放与拖动的码图", Modifier.fillMaxSize().graphicsLayer {
                            scaleX = zoom; scaleY = zoom; translationX = pan.x; translationY = pan.y
                        }, contentScale = ContentScale.Fit)
                    }
                    Text("${image.width} × ${image.height} px · 双指缩放，拖动查看", color = Color.LightGray,
                        fontSize = 12.sp, modifier = Modifier.align(Alignment.CenterHorizontally).padding(16.dp))
                }
            }
        }
    }
}

@Composable
private fun CodeCard(content: @Composable ColumnScope.() -> Unit) {
    Card(Modifier.fillMaxWidth(), colors = CardDefaults.cardColors(containerColor = Color.White)) {
        Column(Modifier.fillMaxWidth().padding(16.dp), verticalArrangement = Arrangement.spacedBy(10.dp), content = content)
    }
}

@Composable
private fun CodeField(value: String, change: (String) -> Unit, label: String, singleLine: Boolean = false) {
    OutlinedTextField(value, { if (it.length <= 8192) change(it) }, modifier = Modifier.fillMaxWidth(), label = { Text(label) }, singleLine = singleLine,
        minLines = if (singleLine) 1 else 3, maxLines = if (singleLine) 1 else 6, shape = RoundedCornerShape(12.dp))
}

@Composable
private fun CodeChoices(options: List<String>, selected: String, select: (String) -> Unit) {
    Row(Modifier.fillMaxWidth().horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
        options.forEach { value -> FilterChip(selected == value, { select(value) }, label = { Text(value) }) }
    }
}

@Composable
private fun CodeSwitch(label: String, checked: Boolean, change: (Boolean) -> Unit) {
    Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically) {
        Text(label, modifier = Modifier.weight(1f), color = Ink, fontSize = 13.sp)
        Switch(checked, change)
    }
}
